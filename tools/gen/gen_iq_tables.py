#!/usr/bin/env python3
"""Emit src/model/iq_tables.h from llama.cpp's codebook tables.

The IQ2/IQ3 codebooks are DATA, not code: the same 256-entry grids every
IQ2_XXS/IQ3_XXS GGUF on disk was quantized against, so a decoder has no
freedom in choosing them. Values are read from a llama.cpp checkout
(ggml/src/ggml-common.h, tables iq2xxs_grid / iq3xxs_grid / ksigns_iq2xs /
kmask_iq2xs) and re-emitted here so fast-llm stays self-contained.

usage: gen_iq_tables.py <path-to-ggml-common.h> > src/model/iq_tables.h
"""
import re, sys

src = open(sys.argv[1]).read()

def table(name):
    m = re.search(r"GGML_TABLE_BEGIN\(\s*(\w+)\s*,\s*" + name +
                  r"\s*,\s*(\d+)\s*\)(.*?)GGML_TABLE_END\(\)", src, re.S)
    if not m:
        sys.exit("table not found: " + name)
    vals = [int(v, 0) for v in
            re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", m.group(3))]
    n = int(m.group(2))
    if len(vals) != n:
        sys.exit("%s: expected %d values, parsed %d" % (name, n, len(vals)))
    return vals

g2, g3 = table("iq2xxs_grid"), table("iq3xxs_grid")
ks, km = table("ksigns_iq2xs"), table("kmask_iq2xs")

# carry-safety invariant relied on by the byte-wise negate in the GPU kernels
lo2 = min((v >> (8 * i)) & 0xFF for v in g2 for i in range(8))
lo3 = min((v >> (8 * i)) & 0xFF for v in g3 for i in range(4))
if lo2 < 1 or lo3 < 1:
    sys.exit("grid contains a zero byte; byte-wise negate would carry")

o = sys.stdout.write
o("// GENERATED by tools/gen/gen_iq_tables.py -- do not edit.\n")
o("// Codebook data for IQ2_XXS / IQ3_XXS, re-emitted from llama.cpp's\n")
o("// ggml-common.h (MIT). These grids are fixed by the file format: a GGUF\n")
o("// was quantized against them, so a decoder cannot choose different ones.\n")
o("// Invariant checked at generation time: every grid byte is >= 1, which is\n")
o("// what makes the byte-wise (x ^ mask) + carry negate free of inter-byte\n")
o("// carries in the GPU kernels.\n")
o("//\n")
o("// Storage: the tables are needed by BOTH host reference code and device\n")
o("// kernels, and a __device__ array is not readable from the host, so each\n")
o("// table is emitted twice under CUDA and reached through FL_HD accessors\n")
o("// that pick by __CUDA_ARCH__. ~3.2 KiB duplicated; the grid then stages\n")
o("// into shared memory once per block (that locality is exactly what Thor's\n")
o("// CPU lacks).\n")
o("#pragma once\n#include <cstdint>\n\n")
o("#if defined(FASTLLM_CUDA) && defined(__CUDACC__)\n")
o("#define FL_IQ_HD __host__ __device__\n#define FL_IQ_DEV static const __device__\n")
o("#else\n#define FL_IQ_HD inline\n#endif\n\nnamespace fastllm {\n\n")

def emit(decl, name, vals, per, fmt):
    o("%s %s[%d] = {\n" % (decl, name, len(vals)))
    for i in range(0, len(vals), per):
        o("    " + ", ".join(fmt % v for v in vals[i:i+per]) + ",\n")
    o("};\n")

def both(name, typ, vals, per, fmt, doc):
    o("// " + doc + "\n")
    emit("static const " + typ, name + "H", vals, per, fmt)
    o("#if defined(FASTLLM_CUDA) && defined(__CUDACC__)\n")
    emit("FL_IQ_DEV " + typ, name + "D", vals, per, fmt)
    o("#endif\n\n")

both("kIq2xxsGrid", "uint64_t", g2, 4, "0x%016xull",
     "256 entries x 8 packed uint8 grid values (2 KiB)")
both("kIq3xxsGrid", "uint32_t", g3, 8, "0x%08xu",
     "256 entries x 4 packed uint8 grid values (1 KiB)")
both("kIqSigns", "uint8_t", ks, 16, "%3d",
     "7-bit sign index -> 8 sign bits (bit j set = negate element j)")
both("kIqSignMask", "uint8_t", km, 8, "%d", "bit j of a sign byte")

for nm in ("kIq2xxsGrid", "kIq3xxsGrid", "kIqSigns", "kIqSignMask"):
    typ = {"kIq2xxsGrid": "uint64_t", "kIq3xxsGrid": "uint32_t"}.get(nm, "uint8_t")
    o("FL_IQ_HD %s fl_%s(int i) {\n" % (typ, nm))
    o("#if defined(FASTLLM_CUDA) && defined(__CUDACC__) && defined(__CUDA_ARCH__)\n")
    o("    return %sD[i];\n#else\n    return %sH[i];\n#endif\n}\n" % (nm, nm))
o("\n} // namespace fastllm\n")
